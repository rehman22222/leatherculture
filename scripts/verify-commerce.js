"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const cheerio = require("cheerio");
const { shippingFor, shippingDetails, returnPolicy } = require("../shop/commerce-schema");
const reviews = require("../shop/product-reviews");
const { reviewSelection, reviewProducts, storefrontReview } = require("../lib/review-input");
const { renderProductPage } = require("../lib/product-renderer");
const { materialize } = require("./build-storefront");
const checkout = { shippingFee: 250, freeShippingFrom: 10000 };
assert.equal(shippingFor(9999, checkout), 250);
assert.equal(shippingFor(10000, checkout), 0);
assert.equal(shippingFor(15000, { ...checkout, freeShippingFrom: 0 }), 250);
assert.equal(shippingDetails(15000, checkout).deliveryTime, undefined, "Do not guess dispatch or transit times");
assert.equal(returnPolicy({ ...checkout, returnsPolicy: "Contact us" }), null, "Do not invent a return window");
const confirmed = { ...checkout, returnsPolicy: "Return undamaged products within 7 days. Customer pays courier.", merchantReturns: { confirmed: true, category: "finite", days: 7, fees: "customer", method: "mail" }, handlingDaysMin: 1, handlingDaysMax: 2, transitDaysMin: 4, transitDaysMax: 5 };
assert.equal(returnPolicy(confirmed).merchantReturnDays, 7);
assert.equal(returnPolicy(confirmed).returnFees, "https://schema.org/ReturnFeesCustomerResponsibility");
assert.equal(returnPolicy({ ...confirmed, merchantReturns: { ...confirmed.merchantReturns, days: "" } }), null);
assert.equal(returnPolicy({ ...confirmed, merchantReturns: { ...confirmed.merchantReturns, confirmed: false } }), null);
assert.equal(returnPolicy({ ...confirmed, merchantReturns: { ...confirmed.merchantReturns, fees: "fixed", feeAmount: 0 } }), null);
assert.equal(shippingDetails(15000, confirmed).deliveryTime.transitTime.minValue, 4);
assert.equal(shippingDetails(15000, { ...confirmed, transitDaysMax: 2 }).deliveryTime.transitTime, undefined);
assert.equal(shippingDetails(15000, { ...checkout, handlingDaysMin: 1, handlingDaysMax: 2 }).deliveryTime.handlingTime.maxValue, 2);
const order = { status: "delivered", items: [{ slug: "the-blade", name: "The Blade" }, { slug: "the-blade", name: "The Blade" }, { slug: "the-heritage", name: "The Heritage" }] };
assert.equal(reviewProducts(order).length, 2);
assert.equal(reviewSelection(order, { rating: 4, productSlug: "the-heritage" }).productSlug, "the-heritage");
assert.equal(reviewSelection(order, { rating: 3 }).productSlug, "", "Order reviews must not count for the first jacket");
assert.throws(() => reviewSelection(order, { rating: 4, productSlug: "not-purchased" }));
for (const rating of [undefined, 0, 6, 2.5, "5"]) assert.throws(() => reviewSelection(order, { rating }));
assert.throws(() => reviewSelection({ ...order, status: "shipped" }, { rating: 4 }));
const base = { id: "r1", productSlug: "the-blade", name: "Test Customer", text: "<script>unsafe</script> Honest customer feedback.", rating: 5, verified: true, status: "approved", createdAt: "2026-10-19" };
const rows = [base, { ...base, id: "r2", rating: 1 }, { ...base, id: "r3", status: "hidden" }, { ...base, id: "r4", productSlug: "the-heritage" }, { ...base, id: "r5", verified: false }, { ...base, id: "r6", productSlug: "" }, base];
assert.equal(reviews.markup(rows, "the-blade").aggregateRating.ratingValue, 3);
assert.equal(reviews.markup(rows, "the-blade").aggregateRating.reviewCount, 2);
assert.deepEqual(reviews.markup([], "the-blade"), {});
assert(!reviews.render(rows, "the-blade").includes("<script>"));
const publicRow = storefrontReview({ ...base, email: "private@example.com", orderId: "private-order", ip: "127.0.0.1", token: "private-token", _id: "internal" });
for (const key of ["email", "orderId", "ip", "token", "_id"]) assert(!(key in publicRow), key);
const product = { slug: "the-blade", name: "The Blade", description: "A jacket", image: "/assets/brand/leather-culture-logo-black.png", price: "Rs 15,000", variants: [{ id: "L", stock: 1, enabled: true, name: "Large" }] };
const settings = { checkout: confirmed, products: [product], productReviews: rows, blogPosts: [], footer: {}, content: { values: {} } };
const html = materialize(renderProductPage(product, settings), settings, "/shop/the-blade", [], "https://www.leatherculture.shop");
const $ = cheerio.load(html);
const nodes = $("script[type='application/ld+json']").toArray().flatMap(e => { const data = JSON.parse($(e).text()); return data["@graph"] || [data]; });
const node = nodes.find(n => n["@type"] === "Product");
assert.equal(node.offers.hasMerchantReturnPolicy.merchantReturnDays, 7, "Materializing a page must preserve confirmed returns");
assert.equal(node.aggregateRating.reviewCount, $(".product-review-list article").length);
assert($("#product-reviews").text().includes("3 / 5"));
assert($(".product-info details").text().includes(confirmed.returnsPolicy));
// Published builds must have consistent shipping and crawlable links on every product page.
const root = path.join(__dirname, "..", "dist");
const sitemap = fs.readFileSync(path.join(root, "sitemap.xml"), "utf8");
for (const match of sitemap.matchAll(/<loc>(.*?)<\/loc>/g)) {
  const url = new URL(match[1]);
  if (!url.pathname.startsWith("/shop/")) continue;
  const page = cheerio.load(fs.readFileSync(path.join(root, url.pathname, "index.html"), "utf8"));
  const data = JSON.parse(page("#lc-product-data").text());
  const productSchema = page("script[type='application/ld+json']").toArray().flatMap(e => { const n = JSON.parse(page(e).text()); return n["@graph"] || [n]; }).find(n => n["@type"] === "Product");
  assert.deepEqual(productSchema.offers.shippingDetails, shippingDetails(Number(productSchema.offers.price), data.checkout));
  assert.deepEqual(productSchema.offers.hasMerchantReturnPolicy || null, returnPolicy(data.checkout));
  assert.equal(page(".product-related a[href^='/shop/']").length, 4);
  assert.equal(page(".product-guides a[href^='/blog/']").length, 3);
  assert(page("#product-reviews").length);
  assert(page(".product-info details").text().includes(data.checkout.returnsPolicy));
}
console.log("Commerce checks passed: shipping, confirmed return policy, review attribution, moderation, privacy and product-page links.");
